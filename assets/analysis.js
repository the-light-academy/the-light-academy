/* =====================================================================
   The Light Academy — на какво се дължат сгрешените задачи
   ---------------------------------------------------------------------
   Таблото показва колко задачи е сгрешил всеки. Това тук казва КАКВИ са
   били — „умножение с 10, 100, 1000“, „ред на действията“, „деление на
   обикновени дроби“ — за да се види какво да се преговаря, а не само
   че нещо куца.

   ОТКЪДЕ ЗНАЕ ВИДА

   От условието на задачата, дума по дума. Записът на един отговор пази
   условието, какво е отговорило детето и кое е вярното, но НЕ пази
   темата. Затова тук стои списък от правила: първото, което съвпадне,
   дава вида.

   Това е разпознаване по признаци, не разбиране. Затова:

   · Правилата са подредени от тясното към широкото. „Умножете по 100“
     трябва да се хване преди общото „умножение на десетични“, инак
     по-широкото правило изяжда по-тясното.
   · Каквото не съвпадне с нищо, отива в „неразпознати“ и СЕ ПОКАЗВА
     отделно, с условията си. Не се натиква в най-близката кофа: по-добре
     преподавателят да види пет задачи и да реши сам, отколкото да му се
     каже уверено нещо невярно.
   · Всяко правило носи `prim` — условие от истинско домашно, което то
     трябва да хване. scripts/analysis-test.js ги пуска всичките и пада,
     ако някое правило спре да хваща своя пример или започне да яде
     чужд.

   ДРОБИТЕ

   В листовете дробите са html (числител над знаменател). Ако този html
   просто се махне, „4/5 · 3/7“ става „45 · 37“ — две безсмислени числа.
   Затова plain() първо ги превръща в „4/5“ и чак после чисти останалите
   етикети.
   ===================================================================== */
(function (global) {
  'use strict';

  var TLA = global.TLA = global.TLA || {};

  var FRAC = /<span class="frac"><span class="num">([\s\S]*?)<\/span><span class="den">([\s\S]*?)<\/span><\/span>/g;

  /* Условието, както го чете правило: дробите стават „n/d“, етикетите
     падат, новите редове стават интервали. */
  function plain(html) {
    return String(html == null ? '' : html)
      .replace(FRAC, function (_, n, d) { return n + '/' + d; })
      .replace(/<[^>]+>/g, ' ')
      .replace(/&nbsp;/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  /* Самият израз, без подканата пред него.

     Това НЕ е украса. „Пресметнете произведението: 0,12 · 0,4“ съдържа
     двоеточие — знакът за деление — и без това отрязване правилото за
     реда на действията виждаше две различни действия там, където е
     едно, и обявяваше половината задачи за „ред на действията“.
     Отрязва се само когато пред двоеточието няма цифра: инак в
     „Разделете на 100: 45,2 : 100“ щеше да падне самото условие. */
  function exprOf(t) {
    var i = t.indexOf(':');
    if (i > 0 && !/\d/.test(t.slice(0, i))) return t.slice(i + 1).trim();
    return t;
  }

  /* Кое е единственото действие в израза: '+' (събиране или изваждане),
     '·' или ':'. null, ако са повече от едно или няма нито едно.

     Нужно е, защото не всяко условие казва с думи какво се иска.
     „Пресметнете: 0,5 + 1,25“ няма нито „съберете“, нито „сума“ — има
     само знак. Без това правило такава задача оставаше неразпозната. */
  function opOf(t) {
    var kinds = {};
    (exprOf(t).match(/[+−·:]/g) || []).forEach(function (o) {
      kinds[o === '−' ? '+' : o] = 1;
    });
    var k = Object.keys(kinds);
    return k.length === 1 ? k[0] : null;
  }

  /* Има ли десетично число (с запетая, както се пише на български). */
  function hasDec(t) { return /\d,\d/.test(t); }
  /* Има ли дроб „n/d“. */
  function hasFrac(t) { return /\d\s*\/\s*\d/.test(t); }

  /* ── правилата ──────────────────────────────────────────────────────
     Подредбата Е правилото. Първото съвпадение печели.                 */
  var RULES = [
    { id: 'round', name: 'Закръгляване',
      test: function (t) { return /закръгл/i.test(t); },
      prim: 'Закръглете 15,368 до стотните.' },

    { id: 'x10', name: 'Умножение и деление с 10, 100 и 1000',
      test: function (t) {
        return /(умнож|раздел|по|на)/i.test(t) && /(^|[^\d,.])(10|100|1000)([^\d,.]|$)/.test(t);
      },
      prim: 'Умножете по 100: 3,456 · 100' },

    { id: 'mixed', name: 'Смесени числа и неправилни дроби',
      test: function (t) { return /смесен|неправилн[аи] дроб|цяла част/i.test(t); },
      prim: 'Превърнете неправилната дроб в смесено число: 23/6' },

    { id: 'props', name: 'Свойства на действията (рационално смятане)',
      test: function (t) { return /рационал|разпределител|по-лесн|наум/i.test(t); },
      prim: 'Пресметнете по най-рационален начин: 3,5 · 4,2 + 3,5 · 5,8' },

    /* Ред на действията: или го пише с думи, или изразът има скоба, или
       в него има ПОВЕЧЕ ОТ ЕДНО различно действие. Последното е
       същината на темата — едно действие няма ред. */
    { id: 'order', name: 'Ред на действията и изрази със скоби',
      test: function (t) {
        if (/стойността на израза|реда на действията/i.test(t)) return true;
        var e = exprOf(t);
        if (/\(/.test(e) && /[+−\-·:*]/.test(e)) return true;
        var kinds = {};
        (e.match(/[+−·:]/g) || []).forEach(function (o) { kinds[o] = 1; });
        return Object.keys(kinds).length >= 2;
      },
      prim: 'Намерете стойността на израза: 12,5 : 5 − 0,4 · 2' },

    { id: 'frac_mul', name: 'Умножение на обикновени дроби',
      test: function (t) {
        return (/умнож|произведение/i.test(t) || opOf(t) === '·') && hasFrac(t) && !hasDec(t);
      },
      prim: 'Умножете дроб с цяло число: 6 · 2/3' },

    { id: 'frac_div', name: 'Деление на обикновени дроби',
      test: function (t) {
        return (/делен|разделете|частно/i.test(t) || opOf(t) === ':') && hasFrac(t) && !hasDec(t);
      },
      prim: 'Разделете цяло число на дроб: 8 : 4/5' },

    { id: 'frac_addsub', name: 'Събиране и изваждане на обикновени дроби',
      test: function (t) {
        return (/събер|сума|извад|разлика|действията/i.test(t) || opOf(t) === '+') &&
               hasFrac(t) && !hasDec(t);
      },
      prim: 'Извършете действията: 3 1/2 − 1 1/4' },

    { id: 'dec_mul', name: 'Умножение на десетични дроби',
      test: function (t) { return (/умнож|произведение/i.test(t) || opOf(t) === '·') && hasDec(t); },
      prim: 'Пресметнете произведението: 0,12 · 0,4' },

    { id: 'dec_div', name: 'Деление на десетични дроби',
      test: function (t) { return (/делен|разделете|частно/i.test(t) || opOf(t) === ':') && hasDec(t); },
      prim: 'Разделете десетична дроб на десетична: 2,25 : 1,5' },

    { id: 'dec_addsub', name: 'Събиране и изваждане на десетични дроби',
      test: function (t) {
        return (/събер|сума|извад|разлика|действията/i.test(t) || opOf(t) === '+') && hasDec(t);
      },
      prim: 'Намерете сумата: 12,75 + 8,3 + 0,125' },

    { id: 'percent', name: 'Процент и част от число',
      test: function (t) { return /процент|%|част от|от числото/i.test(t); },
      prim: 'Колко е 20% от 150?' },

    { id: 'geom', name: 'Геометрия',
      test: function (t) {
        return /триъгълник|ъгъл|ъгли|обиколк|лице|правоъгълник|квадрат|окръжност|диаметър|радиус|успоредн|перпендикуляр/i.test(t);
      },
      prim: 'Триъгълник има ъгли 90°, 45° и 45°. Какъв е той?' },

    /* Текстовата задача е последна нарочно: „165,6 км за 2 часа“ е и
       умножение на десетични, но детето първо трябва да разбере какво
       се пита. Хване ли я по-рано, отчетът казва „умножение“ там,
       където липсва разбиране на условието. */
    { id: 'word', name: 'Текстови задачи',
      test: function (t) {
        return /колко|за колко|намерете колко/i.test(t) &&
               /км|лв|кг|час|минут|литр|ученик|деца|семейств|магазин|цена|стру|изминал|пътува/i.test(t);
      },
      prim: 'Един килограм ябълки струва 2,40 лв. Колко лева ще струват 3,5 кг ябълки?' }
  ];

  var UNKNOWN = { id: 'other', name: 'Неразпознат вид' };

  function classify(text) {
    var t = plain(text);
    for (var i = 0; i < RULES.length; i++) {
      if (RULES[i].test(t)) return RULES[i];
    }
    return UNKNOWN;
  }

  /* „(без отговор)“ и празното не са грешка от неразбиране — детето не е
     стигнало дотам. Броят се отделно, защото съветът е друг. */
  function blank(given) {
    var g = String(given == null ? '' : given).trim();
    return g === '' || g === '-' || /^\(без отговор\)$/i.test(g);
  }

  /* rows: [{ student, title, text, given, correct }] — само сгрешените.
     Връща подредени видове, кой кого е сгрешил, и неразпознатите. */
  function summarise(rows) {
    var byKind = {}, students = {}, blanks = [];

    (rows || []).forEach(function (r) {
      var k = classify(r.text);
      var b = byKind[k.id] || (byKind[k.id] = {
        id: k.id, name: k.name, count: 0, students: {}, examples: []
      });
      b.count++;
      b.students[r.student] = (b.students[r.student] || 0) + 1;
      students[r.student] = (students[r.student] || 0) + 1;
      /* ВСИЧКИ задачи от този вид, не първите няколко. Екранът показва
         само част от тях, но бутонът „Копирай“ дава целия списък — и
         точно по него се вижда КАК греши детето: премества запетаята в
         грешната посока, смята отляво надясно, обръща готовата дроб.
         Няколко примера не стигат за такъв извод. */
      b.examples.push({ student: r.student, title: r.title,
                        text: plain(r.text), given: r.given, correct: r.correct });
      if (blank(r.given)) blanks.push({ student: r.student, text: plain(r.text) });
    });

    var kinds = Object.keys(byKind).map(function (id) { return byKind[id]; });
    /* Подредбата: първо по колко деца го бъркат, после по брой задачи.
       Тема, която куца у ДВАМАТА, е по-важна от тема, в която един е
       сгрешил три пъти — втората е негов пропуск, първата е преподаване. */
    kinds.sort(function (a, b) {
      var da = Object.keys(a.students).length, db = Object.keys(b.students).length;
      if (da !== db) return db - da;
      if (a.count !== b.count) return b.count - a.count;
      return a.name.localeCompare(b.name, 'bg');
    });

    return {
      total: (rows || []).length,
      kinds: kinds,
      students: students,
      blanks: blanks,
      unknown: byKind.other ? byKind.other.count : 0
    };
  }

  TLA.Analysis = {
    plain: plain,
    rules: RULES,
    classify: classify,
    summarise: summarise,
    isBlank: blank
  };
})(typeof window !== 'undefined' ? window : globalThis);
