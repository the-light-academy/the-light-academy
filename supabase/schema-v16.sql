-- =====================================================================
--  The Light Academy — час с група деца
--  ---------------------------------------------------------------------
--  ПУСНИ ЦЕЛИЯ ФАЙЛ. Редакторът на Supabase изпълнява само маркираното,
--  ако има маркирано — файл, пуснат на парчета, оставя базата наполовина.
--
--  Какво прави: разширява едно ограничение в lessons — child_name вече
--  може да е до 200 знака вместо до 80. Нищо друго не се пипа: няма
--  нова колона, няма нови политики, няма нови функции.
--
--  ЗАЩО Е НУЖЕН
--
--  В прозорчето „Нов час“ вече могат да се изберат няколко деца — за
--  час с група. Имената влизат в child_name едно след друго, разделени
--  със запетая: „Мария Иванова, Георги Тодоров, Елена Маринова“. Това е
--  67 знака за три деца; четири-пет вече минават 80 и часът не се
--  записваше, а в екрана излизаше неразбираема грешка от базата.
--
--  ЗАЩО НЕ ОТДЕЛНА ТАБЛИЦА С УЧЕНИЦИ НА ЧАСА
--
--  Така е по-правилно на хартия и някой ден може да се наложи — когато
--  часовете започнат да се броят за всяко дете поотделно. Но днес в
--  lessons стои ИМЕ, а не номер на ученик, и то нарочно: час се записва
--  и за дете, което още не е в платформата (пробен урок, новодошъл).
--  Отделна таблица иска id на ученик за всеки ред — тоест да отпадне
--  точно това. Затова днес се разширява редът, а не се пренарежда
--  базата.
--
--  ЗАЩО 200, А НЕ „колкото дойде“
--
--  Границата пази от залепено есе в полето за име. 200 знака са към
--  осем български имена с фамилии — повече деца в един час няма.
--
--  КОЙ КАКВО МОЖЕ
--
--  Нищо ново. Политиките на lessons са от schema-v11.sql и не се
--  докосват: преподавателят пише своите часове, админът — всички.
--
--  СТРАНИЦАТА РАБОТИ И БЕЗ ТОЗИ ФАЙЛ
--
--  Таблото проверява дължината още преди да прати часа и ако имената
--  надхвърлят 80 знака, казва точно кой файл да се пусне. Един или два
--  ученика се записват и без него, както досега.
-- ---------------------------------------------------------------------


-- ---------------------------------------------------------------------
--  1. Ограничението
-- ---------------------------------------------------------------------
alter table public.lessons
  drop constraint if exists lessons_child_name_ok;

alter table public.lessons
  add constraint lessons_child_name_ok
  check (length(btrim(child_name)) between 1 and 200);

comment on column public.lessons.child_name is
  'Името на детето, а за група — имената едно след друго, разделени със запетая. '
  'Пише се на ръка или се избира от списъка с ученици; детето може и да не е в платформата.';


-- ---------------------------------------------------------------------
--  2. Проверка — какво се получи
-- ---------------------------------------------------------------------
--  горна_граница трябва да е 200. празно_име_минава трябва да е false:
--  разширяването не бива да е изпуснало долната граница.
select
  (select substring(pg_get_constraintdef(oid) from '<= ([0-9]+)')
     from pg_constraint
    where conrelid = 'public.lessons'::regclass
      and conname = 'lessons_child_name_ok')                      as горна_граница,
  (select pg_get_constraintdef(oid) ~ '>= 1'
     from pg_constraint
    where conrelid = 'public.lessons'::regclass
      and conname = 'lessons_child_name_ok') = false              as празно_име_минава,
  (select count(*) from public.lessons
    where length(btrim(child_name)) > 80)                         as часове_с_дълъг_списък;
