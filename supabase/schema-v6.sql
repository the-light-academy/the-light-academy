-- =====================================================================
--  The Light Academy — класирането на цялата академия
--  ---------------------------------------------------------------------
--  ПУСНИ ЦЕЛИЯ ФАЙЛ. Редакторът на Supabase изпълнява само маркираното,
--  ако има маркирано — файл, пуснат на парчета, оставя базата наполовина.
--
--  Какво прави: една-единствена функция. Нищо не се създава и нищо не
--  се пипа: няма нова таблица, няма нова политика, няма промяна по
--  съществуващите. Ако schema-v5.sql още не е пуснат, пусни първо него —
--  двете функции са независими, но състезанието по групи идва оттам.
--
--  КАКВО Е РАЗЛИЧНОТО ОТ my_race()
--
--  my_race() показва групата: същият клас, същият предмет, същият
--  преподавател. Тази тук показва ЦЯЛАТА академия — всеки действащ
--  ученик, без значение в кой клас е и при кого учи, със сбора от
--  всичко предадено по всички предмети. Класът върви до името;
--  преподавателят изобщо не излиза — в едно общо класиране той не е
--  нито обяснение, нито заслуга.
--
--  ЕДНО НЕЩО, КОЕТО ТРЯБВА ДА СЕ ЗНАЕ
--
--  След този файл всяко дете вижда имената, класовете и точките на
--  всички останали в академията — не само на съучениците си. Точно
--  това е смисълът на общото класиране, но е решение, а не подробност.
--  Отдолу пише как се маха с един ред.
--
--  Отдава се точно това: име, клас, точки, възможни точки и дали редът
--  е мой. Нищо друго — без имейли, без дати, без бележки, без
--  преподавател, без кое задание какво е дало.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
--  Класирането на цялата академия
-- ---------------------------------------------------------------------
--  Сметката ТРЯБВА да съвпада с тази в my_race() и в таблото на
--  преподавателя (assets/race.js), иначе едно и също дете ще вижда
--  различни числа на две места:
--
--    * броят се само предадените работи (`status <> 'in_progress'`);
--    * само по публикувани задания;
--    * възможните точки са тези на самата работа, а ако ги няма —
--      тези на заданието.
--
--  Единствената разлика е обхватът: тук НЯМА филтър по предмет, защото
--  общото класиране събира всичко, което детето е решавало.
-- ---------------------------------------------------------------------
create or replace function public.academy_race()
returns table (
  student_name text,
  grade        int,
  points       numeric,
  max_points   numeric,
  is_me        boolean
)
language sql
stable
security definer
set search_path = public
as $$
  with work as (
    select at.user_id,
           at.total_score,
           coalesce(
             nullif(coalesce(at.auto_max, 0) + coalesce(at.manual_max, 0), 0),
             a.max_points, 0) as cap
    from public.attempts at
    join public.assignments a on a.id = at.assignment_id
    where at.status <> 'in_progress'
      and a.published
  )
  -- Ученик без нито една предадена работа ОСТАВА в класирането, с нула.
  -- Затова е left join: „още не е започнал“ е състояние в състезанието,
  -- а не причина детето да го няма никакво.
  select p.full_name,
         public.current_grade(p.id),
         coalesce(sum(w.total_score), 0),
         coalesce(sum(w.cap), 0),
         p.id = auth.uid()
  from public.profiles p
  left join work w on w.user_id = p.id
  where p.role = 'student'
    and p.active
    -- Втората ключалка. Функцията е SECURITY DEFINER и няма филтър по
    -- „кой пита“ — тя връща цялата академия на всекиго. Затова невлязъл
    -- не бива да получи нищо, и това се казва ТУК, а не само с права:
    -- едно сбъркано grant после не отваря списъка.
    and auth.uid() is not null
  group by p.id, p.full_name
  order by 3 desc, 1;
$$;

-- Първата ключалка. Само `grant ... to authenticated` НЕ стига: в
-- Postgres всяка нова функция получава execute от PUBLIC, а `anon` —
-- ролята на публикуемия ключ, който стои в кода на страницата — е част
-- от PUBLIC. Без реда отдолу всеки, който отвори сайта, може да си
-- поиска списъка, без изобщо да влиза.
revoke all on function public.academy_race() from public, anon;
grant execute on function public.academy_race() to authenticated;

-- Същото се отнася и за my_race() от schema-v5.sql. Там пропускът не
-- изтича нищо (функцията тръгва от auth.uid() и на невлязъл връща нула
-- реда), но ключалката е безплатна и мястото ѝ е тук.
revoke all on function public.my_race() from public, anon;
grant execute on function public.my_race() to authenticated;

commit;

-- ---------------------------------------------------------------------
-- Ако трябва да се махне (общото класиране изчезва и от профила на
-- ученика, и от таблото; състезанието по групи остава непокътнато):
--   drop function if exists public.academy_race();
-- ---------------------------------------------------------------------

-- Потвърждение, че е минало. Не raise notice: SQL Editor-ът на Supabase
-- показва само таблици с резултат.
select 'Готово' as статус,
       (select count(*) from pg_proc p
          join pg_namespace n on n.oid = p.pronamespace
         where n.nspname = 'public' and p.proname = 'academy_race') as функцията,
       has_function_privilege('authenticated', 'public.academy_race()', 'execute')
         as влезлите_могат,
       has_function_privilege('anon', 'public.academy_race()', 'execute')
         as невлезлите_могат;
