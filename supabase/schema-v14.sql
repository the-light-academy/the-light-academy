--
--  ЗАЩО Е НУЖНА
--
--  Заглавието казва КАКВО е („Урок — Рационално Гран при“), но не казва
--  какво ще се случи в часа. Под заглавието трябва да стои един ред на
--  човешки език — „Състезание на писта за Формула 1“ — и той се вижда и
--  в календара на преподавателя, и в портала на детето.
--
--  ЗАЩО НЕ В content
--
--  content е jsonb и е на домашните: там стоят задачите, отговорите и
--  точките, и го чете страницата на листа. Описанието е на реда в
--  списъка, не в листа — то трябва да се чете заедно със заглавието, в
--  същата заявка, без да се тегли целият jsonb на всяко задание.
--
--  КОЙ КАКВО МОЖЕ
--
--  Нищо ново. Колоната влиза в таблица, която вече има политики: чете
--  се заедно с останалите колони на реда (ученикът — даденото му,
--  преподавателят и админът — всичко), а пише само админът, както
--  досега. Описанието е текст за показване, не тайна.
--
--  СТРАНИЦИТЕ РАБОТЯТ И БЕЗ ТОЗИ ФАЙЛ
--
--  И календарът, и порталът искат description, но ако колоната я няма,
--  хващат 42703 и повтарят заявката без нея: показва се само
--  заглавието. Тоест файлът може да се пусне и след качването на сайта,
--  без нищо да се чупи междувременно.
-- ---------------------------------------------------------------------

-- ---------------------------------------------------------------------
--  1. Колоната
-- ---------------------------------------------------------------------
alter table public.assignments
  add column if not exists description text;

comment on column public.assignments.description is
  'Един ред под заглавието: какво ще се случи в часа. Показва се в календара и в портала.';

-- Празен низ не е описание — за да не се налага всяка страница да
-- проверява и за null, и за „  “.
alter table public.assignments
  drop constraint if exists assignments_description_not_blank;
alter table public.assignments
  add constraint assignments_description_not_blank
  check (description is null or length(btrim(description)) > 0);

-- ---------------------------------------------------------------------
--  2. Проверка — какво се получи
-- ---------------------------------------------------------------------
select
  (select count(*) from information_schema.columns
    where table_schema = 'public' and table_name = 'assignments'
      and column_name = 'description')                            as има_колона,
  (select count(*) from pg_constraint
    where conrelid = 'public.assignments'::regclass
      and conname = 'assignments_description_not_blank')          as ограничение,
  (select count(*) from public.assignments
    where description is not null)                                as с_описание;
