-- =====================================================================
--  Нов предмет — Състезателна математика
--  ---------------------------------------------------------------------
--  Пуснете целия файл в Supabase → SQL Editor. Може да се пуска колкото
--  пъти искате: ако редът вече го има, нищо не се променя.
--
--  ЗАЩО auto_enroll = false
--  Математика е с auto_enroll = true, тоест всеки нов ученик се записва
--  в нея сам. Състезателната не е такава — тя е за децата, които сами са
--  тръгнали натам. Затова никой не се записва автоматично; записвате ги
--  вие, ученик по ученик, от таблото → Ученици → колоната „Предмети“.
--
--  СЛЕД КАТО ПУСНЕТЕ ТОВА
--    1. Ученици → „Предмети“ → сложете отметка на децата, които ще учат
--       състезателна математика.
--    2. Преподаватели → „Кой кого води“ — за всяко записано дете ще се
--       появи нов ред „Състезателна математика“; изберете кой го води.
--    3. Задания → предметът вече е в падащото меню на всяко задание.
-- =====================================================================

begin;

insert into public.subjects (slug, name, active, auto_enroll, sort_order)
values ('sastezatelna-matematika', 'Състезателна математика', true, false, 20)
on conflict (slug) do nothing;

-- Показва какво има сега, за да се види, че е минало.
do $$
declare row_text text;
begin
  select string_agg(name || ' (' || slug || ')', ', ' order by sort_order)
    into row_text from public.subjects where active;
  raise notice 'Активни предмети: %', row_text;
end $$;

commit;

