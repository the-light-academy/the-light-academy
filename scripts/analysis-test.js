/* Правилата за разпознаване на вида задача — пуска се с `node`.
   Две неща се проверяват и двете са нужни:
   1. всяко правило хваща СВОЯ пример;
   2. нито едно правило не яде чужд пример — тоест редът е верен.
   Второто е същинското: правилата се подреждат от тясното към широкото
   и всяко ново правило може тихо да открадне чужди задачи. */
const g = globalThis; g.window = g;
require('../assets/analysis.js');
const A = window.TLA.Analysis;
let bad = 0;
const chk = (ok, name, extra) => { if (!ok) bad++;
  console.log('   ' + (ok ? '✓' : '✗') + ' ' + name + (extra ? '  · ' + extra : '')); };

console.log('\n══ всяко правило хваща своя пример ══');
A.rules.forEach(r => {
  const got = A.classify(r.prim);
  chk(got.id === r.id, r.name, got.id === r.id ? '' : 'хвана го „' + got.name + '“');
});

console.log('\n══ дробите не се смачкват ══');
const frac = '<span class="frac"><span class="num">4</span><span class="den">5</span></span> · ' +
             '<span class="frac"><span class="num">3</span><span class="den">7</span></span>';
chk(A.plain('Пресметнете произведението: ' + frac) === 'Пресметнете произведението: 4/5 · 3/7',
    'html-дробта става 4/5, не 45', A.plain('x: ' + frac));
chk(A.classify('Пресметнете произведението: ' + frac).id === 'frac_mul',
    'и се разпознава като умножение на дроби');

console.log('\n══ тясното бие широкото ══');
chk(A.classify('Умножете по 100: 3,456 · 100').id === 'x10',
    '„по 100“ не отива при умножение на десетични');
chk(A.classify('Разделете на 100: 45,2 : 100').id === 'x10',
    '„на 100“ не отива при деление на десетични');
chk(A.classify('Пресметнете произведението: 0,12 · 0,4').id === 'dec_mul',
    'а истинското умножение на десетични — да');
chk(A.classify('Автомобил изминал 165,6 км за 2 часа. Колко километра ще измине за 3,5 часа?').id === 'word',
    'текстовата задача не се отчита като умножение');

console.log('\n══ едно действие няма ред ══');
chk(A.classify('Пресметнете: 0,5 + 1,25').id === 'dec_addsub',
    'едно действие не е „ред на действията“',
    A.classify('Пресметнете: 0,5 + 1,25').name);
chk(A.classify('Намерете стойността на израза: 12,5 : 5 − 0,4 · 2').id === 'order',
    'две различни действия — да');

console.log('\n══ непопълненото е отделно от сгрешеното ══');
chk(A.isBlank('(без отговор)') && A.isBlank('-') && A.isBlank(''), 'познава празния отговор');
chk(!A.isBlank('0'), 'но нулата е отговор, не празно');

console.log('\n══ непознатото не се натиква никъде ══');
const un = A.classify('Начертайте нещо съвсем непознато без ключови думи');
chk(un.id === 'other', 'неразпознатото си остава неразпознато', un.name);

console.log(bad ? `\n═══ ПАДНАХА ${bad} ═══` : '\n═══ ВСИЧКО РАБОТИ ═══');
process.exit(bad ? 1 : 0);
